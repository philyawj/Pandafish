package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

func scoreText(s stats) string {
	if s.Score == nil {
		return "n/a"
	}
	return fmt.Sprintf("%.1f%%", *s.Score)
}

func rangeText(s stats) string {
	total := s.Wins + s.Draws + s.Losses + s.Unfinished
	if total == 0 {
		return "n/a"
	}
	lower := 100 * (float64(s.Wins) + float64(s.Draws)/2) / float64(total)
	upper := lower + 100*float64(s.Unfinished)/float64(total)
	return fmt.Sprintf("%.1f%% to %.1f%%", lower, upper)
}

func cell(text string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ", "\r", " ").Replace(text)
}

func report(root string) error {
	files, err := filepath.Glob(filepath.Join(root, "*", "summary.json"))
	if err != nil {
		return err
	}
	type entry struct {
		run summary
		dir string
	}
	var runs []entry
	for _, path := range files {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var s summary
		if err = json.Unmarshal(data, &s); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if s.Schema != 2 {
			return fmt.Errorf("%s: unsupported summary schema %d", path, s.Schema)
		}
		runs = append(runs, entry{s, filepath.Base(filepath.Dir(path))})
	}
	sort.Slice(runs, func(i, j int) bool { return runs[i].run.Created < runs[j].run.Created })
	var table, profiles, timings strings.Builder
	table.WriteString("# Benchmark results\n\nGenerated by the Go benchmark runner. Scores are from the candidate's perspective.\nCompleted score excludes unfinished games. Possible score treats unfinished games as all losses through all wins; it is not a confidence interval.\nForfeits count as losses for the offending engine. Compare matching profiles before interpreting progress.\n\n")
	table.WriteString("| Candidate | Opponent | W / D / L | Unfinished | Forfeits | Completed score | Possible score | Profile | Records |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	profiles.WriteString("\n## Run profiles\n\nTimes are milliseconds. Compare matching timing policies and settings. Partial runs show only completed matchups.\n\n| Profile | Date (UTC) | Move / grace ms | Pairs per opponent | Opening suite / SHA-256 prefix | Move cap | Platform | Timing policy | Match concurrency | Status |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	timings.WriteString("\n## Measured timing\n\nWall time includes sending the position, requesting the move, and receiving bestmove. Attempts past the requested budget may still fit within the explicit protocol allowance; attempts past the full deadline forfeit.\n\n| Profile | Opponent | Candidate max ms | Opponent max ms | Attempts past requested budget (candidate / opponent) |\n| --- | --- | --- | --- | --- |\n")
	for i, r := range runs {
		profile := fmt.Sprintf("R%d", i+1)
		status, policy := "complete", r.run.Settings.TimingPolicy
		if !r.run.Complete {
			status = fmt.Sprintf("partial (%d/%d matchups)", len(r.run.Matches), r.run.PlannedMatches)
		}
		cfg := r.run.Settings
		suite := cfg.OpeningsName
		if suite == "" {
			suite = "unnamed"
		}
		hash := cfg.OpeningsSHA256
		if len(hash) > 8 {
			hash = hash[:8]
		}
		concurrency := fmt.Sprintf("%d (external)", max(1, cfg.ExternalConcurrency))
		if cfg.MatchupConcurrency > 1 {
			concurrency = fmt.Sprintf("%d (all)", cfg.MatchupConcurrency)
		}
		created := r.run.Created
		if parsed, err := time.Parse(time.RFC3339Nano, created); err == nil {
			created = parsed.UTC().Format("2006-01-02 15:04Z")
		}
		platform := r.run.Platform
		if r.run.Machine != "" {
			platform += "; " + r.run.Machine
		}
		fmt.Fprintf(&profiles, "| [%s](%s/summary.json) | %s | %d / %d | %d | %s / %s | %d | %s | %s | %s | %s |\n",
			profile, r.dir, cell(created), cfg.MoveMS, cfg.GraceMS, cfg.Pairs, cell(suite), cell(hash), cfg.MaxPlies, cell(platform), cell(policy), concurrency, status)
		for _, m := range r.run.Matches {
			s := m.Stats
			if m.Games != nil {
				s = summarize(m.Games)
			}
			opponent := m.Engine.Label
			if skill := m.Engine.Options["Skill Level"]; skill != "" && m.Engine.UCIName != "" {
				opponent = m.Engine.UCIName + " / Skill " + skill
			}
			pgn := m.PGN
			if pgn == "" {
				pgn = "games.pgn"
			}
			fmt.Fprintf(&table, "| %s | %s | %d / %d / %d | %d | %d | %s | %s | [%s](%s/summary.json) | [JSON](%s/summary.json), [PGN](%s/%s) |\n",
				cell(r.run.Candidate.Label), cell(opponent), s.Wins, s.Draws, s.Losses, s.Unfinished, s.Forfeits, scoreText(s), rangeText(s), profile, r.dir, r.dir, r.dir, pgn)
			var maximum [2]float64
			var late [2]int
			attempts := 0
			for _, game := range m.Games {
				for _, timing := range game.Timings {
					side := 1
					if timing.Candidate {
						side = 0
					}
					maximum[side] = max(maximum[side], timing.ElapsedMS)
					if timing.ElapsedMS > float64(cfg.MoveMS) {
						late[side]++
					}
					attempts++
				}
			}
			if attempts == 0 {
				fmt.Fprintf(&timings, "| %s | %s | not recorded | not recorded | not recorded |\n", profile, cell(opponent))
			} else {
				fmt.Fprintf(&timings, "| %s | %s | %.1f | %.1f | %d / %d |\n", profile, cell(opponent), maximum[0], maximum[1], late[0], late[1])
			}
		}
	}
	table.WriteString(profiles.String())
	table.WriteString(timings.String())
	return os.WriteFile(filepath.Join(root, "README.md"), []byte(table.String()), 0644)
}
